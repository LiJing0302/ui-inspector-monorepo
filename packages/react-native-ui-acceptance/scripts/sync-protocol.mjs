import { readFile, writeFile } from 'node:fs/promises';

// npm consumers cannot resolve the monorepo's private protocol workspace.
// Vendor the canonical, dependency-free source; --check prevents drift in CI.
const root = new URL('../', import.meta.url);
const canonical = new URL('../inspector-protocol/src/', root);
const index = await readFile(new URL('index.ts', canonical), 'utf8');
const acceptance = await readFile(new URL('acceptance.ts', canonical), 'utf8');
const source = '// Generated by scripts/sync-protocol.mjs. Edit packages/inspector-protocol/src instead.\n'
  + index.replace("export * from './acceptance';", acceptance.trimEnd());
const destination = new URL('src/protocol.ts', root);
if (process.argv.includes('--check')) {
  const current = await readFile(destination, 'utf8').catch(() => '');
  if (current !== source) throw new Error('SDK protocol is stale; run node scripts/sync-protocol.mjs');
} else {
  await writeFile(destination, source);
}
